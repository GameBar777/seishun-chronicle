// 収録用テキストだけに適用する人名の読み替え（画面の表示テキストは変えない）。
// 例: 「澪」が「もお」と読まれた件（2026-10-31）への対策。長い語から順に置換。
const PRON = [['真壁 隼人', 'まかべ はやと'], ['真壁', 'まかべ'], ['隼人', 'はやと'],
  ['氷室澪', 'ひむろ みお'], ['桐生院', 'きりゅういん'], ['早乙女', 'さおとめ'], ['氷室', 'ひむろ'], ['白鷺', 'しらさぎ'], ['速水', 'はやみ'], ['灯野', 'ひの'], ['姫野', 'ひめの'], ['黒瀬', 'くろせ'], ['宙野', 'そらの'],
  ['澪', 'みお'], ['夏帆', 'かほ'], ['麗華', 'れいか'], ['芽衣', 'めい'], ['健太', 'けんた'], ['大吾', 'だいご'], ['真鍋', 'まなべ'], ['湊太', 'そうた'], ['井上', 'いのうえ'], ['暸', 'りょう']];
export function pron(s) {
  for (const [a, b] of PRON) s = s.split(a).join(b);
  return s.replace(/春日(?!和)/g, 'かすが').replace(/凛(?![々と])/g, 'りん'); // 凛々しい・凛とした・春日和は除外
}
